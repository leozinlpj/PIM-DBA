CREATE OR ALTER PROCEDURE SP_RANKING_ESTABELECIMENTOS
AS
BEGIN
    SET NOCOUNT ON;

    WITH RANKING AS
    (
        SELECT
            E.ID_ESTABELECIMENTO,
            E.NOME_FANTASIA,
            C.NOME_CATEGORIA,
            COUNT(N.ID_NPS) AS TOTAL_AVALIACOES,
            CAST(AVG(CAST(N.NPS_GERAL AS DECIMAL(5,2)))
                AS DECIMAL(5,2)) AS MEDIA_AVALIACAO,

            ROW_NUMBER() OVER (
                ORDER BY
                    AVG(CAST(N.NPS_GERAL AS DECIMAL(5,2))) DESC,
                    COUNT(N.ID_NPS) DESC
            ) AS POSICAO

        FROM ESTABELECIMENTO E

        INNER JOIN CATEGORIA C
            ON C.ID_CATEGORIA = E.ID_CATEGORIA

        INNER JOIN NPS N
            ON N.ID_ESTABELECIMENTO = E.ID_ESTABELECIMENTO

        WHERE N.NPS_GERAL IS NOT NULL

        GROUP BY
            E.ID_ESTABELECIMENTO,
            E.NOME_FANTASIA,
            C.NOME_CATEGORIA
    )

    SELECT *
    FROM RANKING
    WHERE POSICAO <= 10
    ORDER BY POSICAO;
END;
GO