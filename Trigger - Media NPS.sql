CREATE OR ALTER TRIGGER TRG_CONVERTE_NPS
ON NPS
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF TRIGGER_NESTLEVEL() > 1
        RETURN;

    UPDATE N
    SET N.NPS_GERAL =
        CASE
            WHEN I.NPS_NOTA IS NULL THEN NULL
            WHEN I.NPS_NOTA = 0 THEN 1
            ELSE CEILING(I.NPS_NOTA / 2.0)
        END
    FROM NPS N
    INNER JOIN inserted I
        ON I.ID_NPS = N.ID_NPS;
END;
GO